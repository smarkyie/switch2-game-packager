"""Protect existing emulator key data while setting up plaintext repacks."""
from pathlib import Path
import sys,tempfile,unittest
sys.path.insert(0,str(Path(__file__).parent/'src'))
import compatibility

class CompatibilityTests(unittest.TestCase):
    def setUp(self):
        scratch=Path(__file__).parent/'test-work';scratch.mkdir(exist_ok=True)
        self.temp=tempfile.TemporaryDirectory(prefix='compat-',dir=scratch);self.root=Path(self.temp.name)
    def tearDown(self):self.temp.cleanup()
    def test_empty_profile_and_repeated_setup(self):
        self.assertFalse(compatibility.inspect(self.root)['ready'])
        result=compatibility.install(self.root);self.assertTrue(result['ready']);self.assertEqual(len(result['added']),2)
        path=self.root/'prod.keys_autogenerated';before=path.read_bytes()
        self.assertEqual(compatibility.install(self.root)['added'],[]);self.assertEqual(path.read_bytes(),before)
        self.assertFalse((self.root/'prod.keys').exists())
    def test_preserves_existing_keys_and_creates_exact_backup(self):
        prod=self.root/'prod.keys';prod.write_bytes(b'header_key = '+b'1'*64+b'\r\n# untouched\r\n')
        target=self.root/'prod.keys_autogenerated';original=b'# existing\r\nother_setting = 123';target.write_bytes(original)
        before=prod.read_bytes();result=compatibility.install(self.root)
        self.assertTrue(result['ready']);self.assertEqual(result['added'],['key_area_key_application_00'])
        self.assertEqual(prod.read_bytes(),before);self.assertTrue(target.read_bytes().startswith(original))
        self.assertEqual(Path(result['backup']).read_bytes(),original)
        self.assertNotIn(b'header_key =',target.read_bytes())
    def test_valid_effective_entries_are_never_replaced(self):
        target=self.root/'prod.keys';target.write_text('HEADER_KEY = '+'a'*64+'\nkey_area_key_application_00 = '+'b'*32+'\n')
        before=target.read_bytes();self.assertEqual(compatibility.install(self.root)['added'],[])
        self.assertEqual(target.read_bytes(),before);self.assertFalse((self.root/'prod.keys_autogenerated').exists())
    def test_invalid_prod_entry_not_masked_by_placeholder(self):
        target=self.root/'prod.keys';target.write_text('header_key = invalid\n')
        before=target.read_bytes()
        with self.assertRaisesRegex(ValueError,'manual correction'):compatibility.install(self.root)
        self.assertEqual(target.read_bytes(),before);self.assertFalse((self.root/'prod.keys_autogenerated').exists())

if __name__=='__main__':unittest.main(verbosity=2)
