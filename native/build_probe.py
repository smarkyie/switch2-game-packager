"""Rebuild the import-free Windows probe payloads; developer tool, no publishing.

Requires ziglang==0.16.0 and pefile==2024.8.26 in the build Python environment.
Run from the project root: python native/build_probe.py --zig /path/to/zig
"""
from pathlib import Path
import argparse,base64,hashlib,json,runpy,subprocess,tempfile,zlib
import pefile

def main():
    parser=argparse.ArgumentParser(description=__doc__);parser.add_argument('--zig',required=True)
    args=parser.parse_args();root=Path(__file__).resolve().parents[1]
    payloads={}
    existing=runpy.run_path(str(root/'src/emulator_payloads.py'))
    legacy=existing.get('LEGACY_PAYLOADS',existing['PAYLOADS'])
    with tempfile.TemporaryDirectory(prefix='s2gp-probe-') as tmp:
        for abi,size_slot,read_slot in (('msvc',3,8),('msvc-read9',3,9),('gnu',4,9),('gnu-read10',4,10)):
            dll=Path(tmp)/('probe-'+abi+'.dll')
            command=[args.zig,'cc','-target','x86_64-windows-gnu','-Os','-fno-stack-protector',
                     '-fno-builtin','-fno-ident','-shared','-nostdlib','-Wl,--entry,DllMain',
                     '-o',str(dll),str(root/'native/container_probe.c')]
            command[5:5]=[f'-DVFS_SIZE_SLOT={size_slot}',f'-DVFS_READ_SLOT={read_slot}']
            subprocess.run(command,check=True)
            pe=pefile.PE(str(dll))
            assert not hasattr(pe,'DIRECTORY_ENTRY_IMPORT') and not hasattr(pe,'DIRECTORY_ENTRY_BASERELOC')
            assert not pe.OPTIONAL_HEADER.DATA_DIRECTORY[9].Size  # no TLS
            image=bytearray(pe.OPTIONAL_HEADER.SizeOfImage)
            for section in pe.sections:
                image[section.VirtualAddress:section.VirtualAddress+section.SizeOfRawData]=section.get_data()
            entry=next(e.address for e in pe.DIRECTORY_ENTRY_EXPORT.symbols if e.name==b'container_probe')
            unwind=[(e.struct.BeginAddress,e.struct.EndAddress,e.struct.UnwindData) for e in pe.DIRECTORY_ENTRY_EXCEPTION]
            payloads[abi]={'entry':entry,'unwind':unwind,'size_slot':size_slot,'read_slot':read_slot,'sha256':hashlib.sha256(image).hexdigest(),
                           'image':base64.b85encode(zlib.compress(image,9)).decode('ascii')}
            pe.close()
    source=hashlib.sha256((root/'native/container_probe.c').read_bytes()).hexdigest()
    (root/'src/emulator_payloads.py').write_text(
        '# Generated by native/build_probe.py with Zig 0.16.0. SPDX-License-Identifier: MIT\n'
        'SOURCE_SHA256 = '+repr(source)+'\nLEGACY_PAYLOADS = '+repr(legacy)+'\nPAYLOADS = '+repr(payloads)+'\n',encoding='utf-8')

if __name__=='__main__':main()
