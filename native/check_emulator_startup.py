"""Check real emulator startup clocks with tiny synthetic containers, no game data.

Windows x64 only. Requires an existing compatible emulator installation. Uses
temporary runtime copies, a separate portable profile and null rendering; never
patches installed executables, touches saves or sends UI input. This checks mode
selection before the deliberately invalid synthetic executable fails to load.
It is not a gameplay or FPS test.
"""
from pathlib import Path
import argparse,json,os,shutil,struct,subprocess,sys,tempfile,uuid
ROOT=Path(__file__).resolve().parents[1]
sys.path.insert(0,str(ROOT/'src'))
import emulator_patch as ep
import container_format as fmt
import engine

def fixture():
    npdm=bytearray(0x480);npdm[:4]=b'META'
    struct.pack_into('<IIII',npdm,0x70,0x80,0x80,0x100,0x380)
    npdm[0x80:0x84]=b'ACI0';npdm[0x400:0x404]=b'ACID'
    program=fmt.nca([fmt.pfs_section(fmt.filesystem([('main.npdm',npdm),('main',b'NSO0'+bytes(256))]))],0x0400111122220000,0)
    container=fmt.filesystem([('program.nca',program)])
    return bytes(npdm),b''.join(container.chunks(1048576))

def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--emulator-folder',required=True,type=Path)
    parser.add_argument('--output-dir',type=Path)
    args=parser.parse_args()
    if sys.platform!='win32':raise ValueError('Run this integration check on Windows x64.')
    folder,state=ep.root_folder(args.emulator_folder);cli=folder/'eden-cli.exe'
    data=cli.read_bytes();profile=ep.profile_for(data,cli.name)
    if profile is None:
        backup=state/(cli.name+'.original')
        if not backup.is_file():raise ValueError('The original CLI executable is not recognized.')
        data=backup.read_bytes();profile=ep.profile_for(data,cli.name)
    if profile is None:raise ValueError('Original CLI loader code is not recognized.')
    scratch=ROOT/'test-work';scratch.mkdir(exist_ok=True)
    output=args.output_dir or scratch/('emulator-startup-'+uuid.uuid4().hex[:10])
    output=output.resolve();output.mkdir(parents=True,exist_ok=True)
    if (output/'results.json').exists():raise ValueError('Choose a new output directory to preserve the previous check.')
    npdm,container=fixture();results=[]
    cases=[('original-12gib-no-companion',data,False,19200000),
           ('original-with-companion',data,True,31250000),
           ('corrected-no-companion',ep.transform(data,profile),False,31250000)]
    if profile['kind']=='inline-pokedinner':
        cases.insert(1,('legacy-patch-no-companion',ep.transform(data,profile,revision=1),False,19200000))
    with tempfile.TemporaryDirectory(prefix='emulator-startup-runtime-',dir=scratch) as tmp:
        runtime=Path(tmp)
        for dll in folder.glob('*.dll'):shutil.copy2(dll,runtime/dll.name)
        (runtime/'user/keys').mkdir(parents=True)
        (runtime/'user/keys/prod.keys_autogenerated').write_text(engine.placeholder_keys(),encoding='utf-8')
        env=os.environ.copy();env['APPDATA']=str(runtime/'appdata');env['LOCALAPPDATA']=str(runtime/'localappdata')
        for name in list(env):
            if name.startswith('EDEN_NX2_'):env.pop(name)
        for name,binary,companion,expected in cases:
            case=runtime/name;case.mkdir();(case/'Game.nsp').write_bytes(container)
            if companion:(case/'main.npdm').write_bytes(npdm)
            exe=runtime/'eden-cli.exe';exe.write_bytes(binary)
            config=case/'sdl.ini';config.write_text('[Core]\nmemory_layout_mode=4\n[Renderer]\nbackend=2\n[WebService]\nenable_telemetry=false\n')
            process=subprocess.Popen([str(exe),'-n','-c',str(config),str(case/'Game.nsp')],cwd=runtime,env=env,
                                     stdin=subprocess.DEVNULL,stdout=subprocess.DEVNULL,stderr=subprocess.DEVNULL,
                                     creationflags=subprocess.CREATE_NO_WINDOW)
            try:exit_code=process.wait(timeout=15)
            except subprocess.TimeoutExpired:
                process.terminate();process.wait(timeout=5);raise RuntimeError('Startup timed out: '+name)
            logfile=runtime/'user/log/eden_log.txt'
            if not logfile.exists():raise RuntimeError(f'{name}: emulator exited before creating its startup log (exit {exit_code:#x}); check its runtime dependencies.')
            log=logfile.read_text(encoding='utf-8',errors='replace')
            (output/(name+'.log')).write_text(log,encoding='utf-8')
            matched=f'Guest counter frequency: {expected} Hz' in log
            results.append({'case':name,'expected_counter_hz':expected,'matched':matched,'exit_code':exit_code})
            print(json.dumps(results[-1]),flush=True)
            if not matched:raise AssertionError('Incorrect startup mode: '+name)
    report={'build':profile['name'],'original_sha256':ep.digest(data),'cases':results,
            'installed_emulator_modified':False,'gameplay_or_fps_tested':False}
    (output/'results.json').write_text(json.dumps(report,indent=2),encoding='utf-8')
    print('Startup-mode checks passed. Logs: '+str(output),flush=True)

if __name__=='__main__':main()
